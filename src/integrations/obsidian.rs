use std::collections::HashSet;
use std::fs;
use std::path::{Path, PathBuf};

use amane::Color;

use super::{config_home, hex, home, write};
use crate::theme::Theme;

fn rgb(color: Color) -> String {
    format!("{}, {}, {}", color.red(), color.green(), color.blue())
}

fn find_vaults() -> Vec<PathBuf> {
    let mut vaults = HashSet::new();

    let candidate_configs = [
        format!("{}/.var/app/md.obsidian.Obsidian/config/obsidian/obsidian.json", home()),
        format!("{}/obsidian/obsidian.json", config_home()),
    ];

    for cfg in &candidate_configs {
        if let Ok(content) = fs::read_to_string(cfg) {
            if let Ok(v) = serde_json::from_str::<serde_json::Value>(&content) {
                if let Some(vault_obj) = v.get("vaults").and_then(|v| v.as_object()) {
                    for (_id, item) in vault_obj {
                        if let Some(p) = item.get("path").and_then(|p| p.as_str()) {
                            let path = PathBuf::from(p);
                            if path.exists() {
                                vaults.insert(path);
                            }
                        }
                    }
                }
            }
        }
    }

    let notes_mnt = PathBuf::from("/mnt/ansible/Notes");
    if notes_mnt.exists() {
        vaults.insert(notes_mnt);
    }

    let doc_notes = PathBuf::from(format!("{}/Documents/Notes", home()));
    if doc_notes.exists() {
        vaults.insert(doc_notes);
    }

    let doc_vault = PathBuf::from(format!("{}/Documents/Obsidian Vault", home()));
    if doc_vault.exists() {
        vaults.insert(doc_vault);
    }

    vaults.into_iter().collect()
}

pub fn export(theme: &Theme) {
    let vaults = find_vaults();
    if vaults.is_empty() {
        return;
    }

    let accent_hex = hex(theme.accent);
    let accent_hover_hex = hex(theme.accent_hover);
    let bg_hex = hex(theme.background);
    let surface_hex = hex(theme.surface);
    let border_hex = hex(theme.border);
    let fg_hex = hex(theme.text);
    let muted_hex = hex(theme.muted_text);
    let secondary_hex = hex(theme.secondary_text);

    let accent_rgb = rgb(theme.accent);
    let bg_rgb = rgb(theme.background);
    let surface_rgb = rgb(theme.surface);
    let border_rgb = rgb(theme.border);
    let fg_rgb = rgb(theme.text);
    let muted_rgb = rgb(theme.muted_text);
    let secondary_rgb = rgb(theme.secondary_text);

    let css = format!(
        r#"/* generated by amane, do not edit */
body, .theme-dark, .theme-light {{
  /* Core Obsidian Tokens */
  --color-accent: {accent_hex} !important;
  --color-accent-hover: {accent_hover_hex} !important;
  --interactive-accent: {accent_hex} !important;
  --interactive-accent-hover: {accent_hover_hex} !important;
  --text-accent: {accent_hex} !important;
  --text-accent-hover: {accent_hover_hex} !important;

  --background-primary: {bg_hex} !important;
  --background-primary-alt: {surface_hex} !important;
  --background-secondary: {surface_hex} !important;
  --background-secondary-alt: {bg_hex} !important;
  --background-modifier-border: {border_hex} !important;
  --background-modifier-border-hover: {accent_hex} !important;
  --background-modifier-border-focus: {accent_hex} !important;
  --background-modifier-hover: rgba({accent_rgb}, 0.15) !important;

  --text-normal: {fg_hex} !important;
  --text-muted: {muted_hex} !important;
  --text-faint: {secondary_hex} !important;

  --titlebar-background: {surface_hex} !important;
  --titlebar-background-focused: {surface_hex} !important;
  --tab-background-active: {bg_hex} !important;
  --tab-text-color-active: {accent_hex} !important;
  --nav-item-color-active: {accent_hex} !important;
  --nav-item-background-active: rgba({accent_rgb}, 0.18) !important;
  --nav-item-background-hover: rgba({accent_rgb}, 0.10) !important;

  --code-background: {surface_hex} !important;
  --code-normal: {fg_hex} !important;

  /* Catppuccin Theme Variable Mappings */
  --ctp-base: {bg_rgb} !important;
  --ctp-mantle: {surface_rgb} !important;
  --ctp-crust: {surface_rgb} !important;
  --ctp-text: {fg_rgb} !important;
  --ctp-accent: {accent_rgb} !important;
  --ctp-subtext1: {muted_rgb} !important;
  --ctp-subtext0: {muted_rgb} !important;
  --ctp-overlay2: {secondary_rgb} !important;
  --ctp-overlay1: {border_rgb} !important;
  --ctp-overlay0: {border_rgb} !important;
  --ctp-surface2: {border_rgb} !important;
  --ctp-surface1: {surface_rgb} !important;
  --ctp-surface0: {surface_rgb} !important;
}}
"#
    );

    for vault in vaults {
        let dot_obsidian = vault.join(".obsidian");
        if !dot_obsidian.exists() {
            continue;
        }

        let snippet_dir = dot_obsidian.join("snippets");
        let _ = fs::create_dir_all(&snippet_dir);
        let snippet_path = snippet_dir.join("amane.css");
        write(&snippet_path.to_string_lossy(), &css);

        sync_appearance(&dot_obsidian, &accent_hex);
    }
}

fn sync_appearance(dot_obsidian: &Path, accent_hex: &str) {
    let appearance_path = dot_obsidian.join("appearance.json");
    let mut config: serde_json::Value = if let Ok(data) = fs::read_to_string(&appearance_path) {
        serde_json::from_str(&data).unwrap_or_else(|_| serde_json::json!({}))
    } else {
        serde_json::json!({})
    };

    if !config.is_object() {
        config = serde_json::json!({});
    }

    let mut changed = false;

    if config.get("accentColor").and_then(|v| v.as_str()) != Some(accent_hex) {
        config["accentColor"] = serde_json::json!(accent_hex);
        changed = true;
    }

    let snippets = config.entry("enabledCssSnippets").or_insert_with(|| serde_json::json!([]));
    if let Some(arr) = snippets.as_array_mut() {
        if !arr.iter().any(|v| v.as_str() == Some("amane")) {
            arr.push(serde_json::json!("amane"));
            changed = true;
        }
    } else {
        *snippets = serde_json::json!(["amane"]);
        changed = true;
    }

    if changed {
        if let Ok(pretty) = serde_json::to_string_pretty(&config) {
            write(&appearance_path.to_string_lossy(), &pretty);
        }
    }
}
